export const DEFAULT_PROFILE = PROFILES[0];

/** 按产品名优先、再按 VID/PID 猜机型（名字能区分共用 PID 的竹二和 Kiwi） */
export function detectProfile(device) {
  if (!device) return null;
  const vid = device.vendorId;
  const pid = device.productId;
  const name = (device.productName || '').trim().toLowerCase();

  for (const p of PROFILES) {
    if (p.exactNames?.some((n) => name === n)) return p;
  }
  for (const p of PROFILES) {
    if (p.names?.some((n) => name.includes(n))) return p;
  }

  for (const p of PROFILES) {
    if (p.nameExcludes?.some((n) => name.includes(n))) continue;
    if (p.nameIncludes && !p.nameIncludes.some((n) => name.includes(n))) continue;

    const wantVid = p.match?.vendorId ?? p.vendorId;
    if (wantVid != null && wantVid !== vid) continue;
    const pids = p.productIds ?? (p.match?.productId != null ? [p.match.productId] : []);
    if (!pids.length) continue;
    if (pids.includes(pid)) return p;
  }
  return null;
}

/** 机型的读/写寄存器地址表 */
export function registersOf(profile) {
  const p = profile || DEFAULT_PROFILE;
  if (Array.isArray(p.bandRegisters)) {
    return {
      gainFreq: (i) => p.bandRegisters[i].gainFreq ?? p.bandRegisters[i].freq,
      q: (i) => p.bandRegisters[i].q,
      slot: p.slotRegister ?? 0x24,
    };
  }
  const base = p.baseRegister ?? 0x26;
  return {
    gainFreq: (i) => base + i * 2,
    q: (i) => base + i * 2 + 1,
    slot: p.slotRegister ?? 0x24,
  };
}
